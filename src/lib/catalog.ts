export function dsoFamily(type: string): 'galaxy' | 'cluster' | 'nebula' {
  if (['g', 's', 's0', 'i', 'e'].includes(type)) return 'galaxy';
  if (['oc', 'gc'].includes(type)) return 'cluster';
  return 'nebula';
}

